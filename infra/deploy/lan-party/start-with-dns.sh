#!/usr/bin/env bash
# Detect host LAN IP → .env.runtime → prepare WebGL for HTTP → start full stack.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

# shellcheck source=detect-host-lan-ip.sh
source "${ROOT}/detect-host-lan-ip.sh"

DNS_ONLY=false
REBAKE=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dns-only) DNS_ONLY=true; shift ;;
    --rebake-dashboard) REBAKE=true; shift ;;
    # backwards compat
    --all) DNS_ONLY=false; shift ;;
    -h | --help)
      echo "Usage: $0 [--dns-only] [--rebake-dashboard]"
      echo "  Detects host IPv4, writes .env.runtime, prepares WebGL for plain HTTP"
      echo "  (decompress .br — Firefox cannot use Brotli over HTTP), starts full stack."
      echo "  --dns-only          only start dnsmasq"
      echo "  --rebake-dashboard  rebuild web-dashboard with VITE_* for detected IP"
      echo "                      (also if IP changed vs previous .env.runtime)"
      exit 0
      ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done

IP="$(detect_host_lan_ipv4)" || {
  echo "detect-host-lan-ip: no suitable IPv4 (need LAN/Wi‑Fi or tailscale0)" >&2
  exit 1
}

PREV_IP=""
RUNTIME="${ROOT}/.env.runtime"
if [[ -f "$RUNTIME" ]]; then
  PREV_IP="$(awk -F= '/^SERVER_LAN_IP=/{print $2; exit}' "$RUNTIME" || true)"
fi

cat >"$RUNTIME" <<EOF
# Generated by start-with-dns.sh at $(date -Iseconds) — do not commit.
SERVER_LAN_IP=${IP}
DNSMASQ_BIND_IP=${IP}
DASHBOARD_PUBLIC_URL=http://${IP}:5173
VITE_API_BASE_URL=
VITE_WEBGL_BASE_URL=http://${IP}:8080/
S3_ENDPOINT=http://${IP}:9000
EOF

ENV_FILES=(--env-file "${ROOT}/.env")
[[ -f "${ROOT}/.env" ]] || {
  echo "Missing ${ROOT}/.env — copy from .env.example" >&2
  exit 1
}
ENV_FILES+=(--env-file "$RUNTIME")

echo "SERVER_LAN_IP=${IP} DNSMASQ_BIND_IP=${IP}"
echo "VITE_WEBGL_BASE_URL=http://${IP}:8080/  VITE_API_BASE_URL=(same-origin /api)"
echo "→ ${RUNTIME}"

# Firefox: Brotli only over HTTPS — expand .br for museum HTTP.
bash "${ROOT}/prepare-webgl-http.sh"

if [[ "$REBAKE" == true || ( -n "$PREV_IP" && "$PREV_IP" != "$IP" ) ]]; then
  echo "Rebuilding web-dashboard for IP ${IP} (was: ${PREV_IP:-none})…"
  docker compose "${ENV_FILES[@]}" build web-dashboard
fi

COMPOSE=(-f docker-compose.yml -f docker-compose.discover.yml)

if [[ "$DNS_ONLY" == true ]]; then
  docker compose "${ENV_FILES[@]}" "${COMPOSE[@]}" up -d dnsmasq
else
  # Full stack + UDP lan-discover beacon (observer / Quest discovery).
  docker compose "${ENV_FILES[@]}" "${COMPOSE[@]}" up -d
  if [[ "$REBAKE" == true || ( -n "$PREV_IP" && "$PREV_IP" != "$IP" ) ]]; then
    docker compose "${ENV_FILES[@]}" "${COMPOSE[@]}" up -d --force-recreate web-dashboard
  fi
fi

echo "Verify DNS:  dig @${IP} clients3.google.com +short"
echo "Verify UI:   curl -I http://${IP}:5173/"
echo "Verify GL:   curl -I http://${IP}:8080/Build/web%20build.framework.js"
